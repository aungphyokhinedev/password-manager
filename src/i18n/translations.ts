export const translations: Record<Language, Translations> = { en, my, zh, ja, ko }

export type ErrorCode = keyof Translations['errors']

export function translateError(code: ErrorCode, lang: Language): string {
  return translations[lang].errors[code]
}

export function interpolate(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? ''))
}
